/**
 * api-codegen.service.ts
 * ──────────────────────
 * The full-code escape hatch. Emits the catalogue as a self-contained, owned
 * test project the customer runs in their own repo and IDE — no lock-in:
 *
 *   • target 'playwright' → a @playwright/test API project (one spec per host),
 *     CI workflow, config, README.
 *   • target 'k6'        → a k6 load/smoke script.
 *   • always: Monitoring-as-Code (monitors.yaml) — declarative synthetic
 *     monitors per endpoint, and a local-first authoring config
 *     (intelliqe.config.json) that round-trips edits back into the workspace.
 *
 * Standalone, opt-in, pure string generation — no IO, no pipeline coupling.
 * The result is a list of files the client offers to download.
 */
export interface CodegenEndpoint {
  method: string; url: string; title?: string; expectedStatus?: number;
  headers?: { key: string; value: string }[];
  auth?: { type?: string; headerName?: string };
  body?: string;
}
export type CodegenTarget = 'playwright' | 'k6';
export interface CodeFile { path: string; language: string; content: string }
export interface CodegenResult { target: CodegenTarget; projectName: string; files: CodeFile[]; fileCount: number }

function safeName(s: string, fallback: string): string {
  const v = String(s || '').trim().toLowerCase().replace(/[^a-z0-9-_]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
  return v || fallback;
}
function host(u: string): string { try { return new URL(u).host; } catch { return ''; } }
function pathOf(u: string): string { try { return new URL(u).pathname || '/'; } catch { return u; } }
function originOf(u: string): string { try { return new URL(u).origin; } catch { return ''; } }
function jsStr(s: string): string { return JSON.stringify(String(s ?? '')); }

function groupByHost(eps: CodegenEndpoint[]): Map<string, CodegenEndpoint[]> {
  const m = new Map<string, CodegenEndpoint[]>();
  for (const e of eps) { const h = host(e.url) || 'api'; if (!m.has(h)) m.set(h, []); m.get(h)!.push(e); }
  return m;
}

/** Auth header → env-var reference, so no secret is baked into the emitted code. */
function authHeader(e: CodegenEndpoint): { name: string; envVar: string } | null {
  const t = (e.auth?.type || 'none').toLowerCase();
  if (t === 'none' || !t) return null;
  if (t === 'bearer') return { name: 'Authorization', envVar: 'API_BEARER_TOKEN' };
  if (t === 'basic') return { name: 'Authorization', envVar: 'API_BASIC_AUTH' };
  if (t === 'apikey') return { name: e.auth?.headerName || 'X-API-Key', envVar: 'API_KEY' };
  return null;
}

function playwrightSpec(h: string, eps: CodegenEndpoint[]): string {
  const lines: string[] = [
    "import { test, expect } from '@playwright/test';",
    '',
    `// Generated from the IntelliQE catalogue — host ${h}. Edit freely; this is your code.`,
    `test.describe(${jsStr(h)}, () => {`,
  ];
  for (const e of eps) {
    const method = (e.method || 'GET').toUpperCase();
    const status = e.expectedStatus || 200;
    const title = e.title || `${method} ${pathOf(e.url)}`;
    const ah = authHeader(e);
    const headers: string[] = (e.headers || []).filter((hd) => hd.key).map((hd) => `        ${jsStr(hd.key)}: ${jsStr(hd.value)},`);
    if (ah) headers.push(`        ${jsStr(ah.name)}: process.env.${ah.envVar} ?? '',`);
    const hasBody = ['POST', 'PUT', 'PATCH'].includes(method) && e.body;
    lines.push(
      `  test(${jsStr(title)}, async ({ request }) => {`,
      `    const res = await request.fetch(${jsStr(e.url)}, {`,
      `      method: ${jsStr(method)},`,
      headers.length ? `      headers: {\n${headers.join('\n')}\n      },` : '',
      hasBody ? `      data: ${jsStr(e.body!)},` : '',
      `    });`,
      `    expect(res.status()).toBe(${status});`,
      `  });`,
    );
  }
  lines.push('});', '');
  return lines.filter((l) => l !== '').join('\n') + '\n';
}

function playwrightProject(name: string, eps: CodegenEndpoint[]): CodeFile[] {
  const byHost = groupByHost(eps);
  const files: CodeFile[] = [];
  for (const [h, list] of byHost) files.push({ path: `tests/${safeName(h, 'api')}.spec.ts`, language: 'typescript', content: playwrightSpec(h, list) });

  files.push({ path: 'playwright.config.ts', language: 'typescript', content:
`import { defineConfig } from '@playwright/test';

// Generated by IntelliQE — owned, lock-in-free. Secrets come from the env.
export default defineConfig({
  testDir: './tests',
  reporter: [['list'], ['html', { open: 'never' }], ['junit', { outputFile: 'results/junit.xml' }]],
  use: { extraHTTPHeaders: {} },
  retries: process.env.CI ? 1 : 0,
});
` });

  files.push({ path: 'package.json', language: 'json', content:
`{
  "name": ${jsStr(name)},
  "private": true,
  "type": "module",
  "scripts": {
    "test": "playwright test",
    "report": "playwright show-report"
  },
  "devDependencies": {
    "@playwright/test": "^1.49.1"
  }
}
` });

  files.push({ path: '.github/workflows/api-tests.yml', language: 'yaml', content:
`name: API tests
on: [push, workflow_dispatch]
jobs:
  test:
    runs-on: ubuntu-latest
    env:
      API_BEARER_TOKEN: \${{ secrets.API_BEARER_TOKEN }}
      API_KEY: \${{ secrets.API_KEY }}
      API_BASIC_AUTH: \${{ secrets.API_BASIC_AUTH }}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with: { node-version: 20 }
      - run: npm ci || npm install
      - run: npx playwright install --with-deps
      - run: npm test
` });

  files.push({ path: 'README.md', language: 'markdown', content:
`# ${name}

Generated from the IntelliQE catalogue — **your code, no lock-in**. Run it locally
in any IDE, commit it, and keep editing. Changes round-trip back into IntelliQE
via \`intelliqe.config.json\` (local-first authoring).

## Run
\`\`\`bash
npm install
npx playwright install
API_BEARER_TOKEN=... npm test
\`\`\`

Secrets are read from the environment — none are baked into the specs.

## Files
- \`tests/*.spec.ts\` — one spec per API host, a test per endpoint.
- \`monitoring/monitors.yaml\` — Monitoring-as-Code (synthetic monitors).
- \`intelliqe.config.json\` — local-first authoring + sync manifest.
- \`.github/workflows/api-tests.yml\` — CI.
` });

  return files;
}

function k6Project(name: string, eps: CodegenEndpoint[]): CodeFile[] {
  const reqs = eps.map((e) => {
    const method = (e.method || 'GET').toUpperCase();
    const ah = authHeader(e);
    const headerObj = `{ ${[...(e.headers || []).filter((h) => h.key).map((h) => `${jsStr(h.key)}: ${jsStr(h.value)}`), ...(ah ? [`${jsStr(ah.name)}: __ENV.${ah.envVar} || ''`] : [])].join(', ')} }`;
    const hasBody = ['POST', 'PUT', 'PATCH'].includes(method) && e.body;
    return `  {
    const res = http.request(${jsStr(method)}, ${jsStr(e.url)}, ${hasBody ? jsStr(e.body!) : 'null'}, { headers: ${headerObj} });
    check(res, { ${jsStr((e.title || `${method} ${pathOf(e.url)}`) + ` → ${e.expectedStatus || 200}`)}: (r) => r.status === ${e.expectedStatus || 200} });
  }`;
  }).join('\n');
  return [{ path: `${safeName(name, 'load')}.k6.js`, language: 'javascript', content:
`import http from 'k6/http';
import { check, sleep } from 'k6';

// Generated by IntelliQE — k6 smoke/load script. Run:  k6 run ${safeName(name, 'load')}.k6.js
export const options = {
  stages: [
    { duration: '30s', target: 10 },
    { duration: '1m', target: 10 },
    { duration: '20s', target: 0 },
  ],
  thresholds: { http_req_failed: ['rate<0.01'], http_req_duration: ['p(95)<800'] },
};

export default function () {
${reqs}
  sleep(1);
}
` }];
}

function monitorsYaml(name: string, eps: CodegenEndpoint[]): string {
  const monitors = eps.map((e) => {
    const method = (e.method || 'GET').toUpperCase();
    const ah = authHeader(e);
    return `  - name: ${JSON.stringify(e.title || `${method} ${pathOf(e.url)}`)}
    request:
      method: ${method}
      url: ${JSON.stringify(e.url)}${ah ? `
      headers:
        ${ah.name}: "\${${ah.envVar}}"` : ''}
    assert:
      status: ${e.expectedStatus || 200}
      maxResponseMs: 2000
    schedule:
      everyMinutes: 5
      regions: [eu, us]`;
  }).join('\n');
  return `# Monitoring-as-Code — generated by IntelliQE.
# Declarative synthetic monitors. Apply with your scheduler / CI:  intelliqe monitors apply monitoring/monitors.yaml
version: 1
name: ${JSON.stringify(name)}
defaults:
  alert:
    channels: [slack, email]
    on: [failure, recovery]
monitors:
${monitors}
`;
}

function intelliqeConfig(name: string, target: CodegenTarget, eps: CodegenEndpoint[]): string {
  return JSON.stringify({
    version: 1,
    project: name,
    localFirst: true,
    target,
    authoring: {
      testsDir: target === 'playwright' ? 'tests' : '.',
      monitors: 'monitoring/monitors.yaml',
      editor: 'any',
    },
    sync: {
      // Push edits made locally back into the IntelliQE catalogue (opt-in).
      endpoint: '/api/v1/public/api-automation/import/connector',
      direction: 'two-way',
    },
    endpoints: eps.map((e) => ({ method: (e.method || 'GET').toUpperCase(), url: e.url, base: originOf(e.url) })),
  }, null, 2);
}

export function generateCodeProject(input: { endpoints: CodegenEndpoint[]; target?: CodegenTarget; projectName?: string }): CodegenResult {
  const target: CodegenTarget = input.target === 'k6' ? 'k6' : 'playwright';
  const name = safeName(input.projectName || 'intelliqe-api-tests', 'intelliqe-api-tests');
  const eps = (input.endpoints || []).filter((e) => e && /^https?:\/\//i.test(String(e.url || ''))).slice(0, 1000);
  if (!eps.length) throw new Error('No endpoints to generate from. Select at least one endpoint with an absolute URL.');

  const files: CodeFile[] = target === 'k6' ? k6Project(name, eps) : playwrightProject(name, eps);
  files.push({ path: 'monitoring/monitors.yaml', language: 'yaml', content: monitorsYaml(name, eps) });
  files.push({ path: 'intelliqe.config.json', language: 'json', content: intelliqeConfig(name, target, eps) });

  return { target, projectName: name, files, fileCount: files.length };
}
